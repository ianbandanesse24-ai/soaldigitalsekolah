export function createEmptyQuestion(
  nomor: number,
  type: QuestionType,
  mataPelajaran: string,
  bab?: BabMateriConfig,
  indexWithinBab = 0,
  fase = 'Fase E',
  kelas = 'Kelas X (10)'
): QuestionItem {
  const id = `q_${Date.now()}_${nomor}_${Math.random().toString(36).slice(2, 7)}`;
  const defaultBobot =
    type === 'PG' ? 2 : type === 'JAWABAN_SINGKAT' ? 3 : type === 'MENJODOHKAN' ? 4 : 10;

  const materiLabel = bab
    ? `${bab.namaBab}${bab.lingkupMateri ? ` — ${bab.lingkupMateri}` : ''}`
    : `Topik Inti ${nomor}`;

  const regCode = isAgamaBudiPekertiSubject(mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  const cpText = bab?.capaianPembelajaran
    ? `${bab.capaianPembelajaran}${bab.elemenCp ? ` [Elemen: ${bab.elemenCp}]` : ''}`
    : `Memahami secara mendalam konsep pada ${materiLabel} mata pelajaran ${mataPelajaran} (${regShort}).`;

  const defaultLevel: CognitiveLevel =
    type === 'ESAY' ? 'C4' : type === 'PG' ? 'C2' : 'C3';
  const defaultTier = tierFromCognitiveLevel(defaultLevel);

  const tpList = (bab?.tujuanPembelajaranList || []).filter((t) => t.trim().length > 0);
  const chosenTp =
    tpList.length > 0
      ? pickTpForCognitiveLevel(tpList, defaultLevel, defaultTier)
      : pickTpForCognitiveLevel(
          buildDefaultTpsForBab(
            bab?.namaBab || `Bab ${nomor}`,
            bab?.lingkupMateri || materiLabel,
            mataPelajaran,
            fase,
            bab?.capaianPembelajaran
          ),
          defaultLevel,
          defaultTier
        );

  const tempMeta: ExamMetadata = {
    ...INITIAL_METADATA,
    mataPelajaran,
    kelas,
    fase,
    kelasSemester: `${kelas} / ${fase}`,
    babMateriList: bab ? [bab] : [],
  };

  const baseQuestion: QuestionItem = {
    id,
    nomor,
    type,
    babId: bab?.id,
    namaBab: bab?.namaBab,
    kdCp: cpText,
    tujuanPembelajaran: chosenTp,
    materi: materiLabel,
    indikator: '',
    levelKognitif: defaultLevel,
    tingkatanSoal: defaultTier,
    bobot: defaultBobot,
    sumberBuku: `Panduan ${mataPelajaran} ${kelas} (${fase}) · ${regShort} (${KURIKULUM_TETAP})`,
    rumusanSoal: '',
    opsiPg: {
      A: '',
      B: '',
      C: '',
      D: '',
      E: '',
    },
    useOptionE: true,
    kunciPg: 'A',
    kunciEsai: '',
    kunciSingkat: '',
    pasanganMenjodohkan: [],
    pembahasan: '',
    catatanTelaah: `Layak digunakan (selaras ${regShort} & ${KURIKULUM_TETAP}).`,
    customFields: {},
    isAutoDraft: true,
  };

  baseQuestion.indikator = generateSmartIndikatorAbcd(
    baseQuestion,
    tempMeta,
    chosenTp
  );

  return generateSmartDraftContentForQuestion(
    baseQuestion,
    tempMeta,
    chosenTp,
    true,
    true,
    indexWithinBab * 13 + nomor * 17
  );
}

export function distributeTotalAcrossCheckedTypes(
  total: number,
  selectedTypes: Record<QuestionType, boolean>
): Record<QuestionType, number> {
  const order: QuestionType[] = ['PG', 'JAWABAN_SINGKAT', 'MENJODOHKAN', 'ESAY'];
  const active = order.filter((t) => selectedTypes[t]);
  const result: Record<QuestionType, number> = {
    PG: 0,
    JAWABAN_SINGKAT: 0,
    MENJODOHKAN: 0,
    ESAY: 0,
  };
  if (active.length === 0 || total <= 0) return result;

  if (active.includes('PG') && active.length > 1 && total >= active.length) {
    // Beri porsi PG sedikit lebih besar secara wajar, sisanya dibagi rata
    const pgShare = Math.max(1, Math.round(total * 0.45));
    const maxPg = total - (active.length - 1);
    result.PG = Math.min(pgShare, maxPg);
    const remaining = total - result.PG;
    const others = active.filter((t) => t !== 'PG');
    const base = Math.floor(remaining / others.length);
    let mod = remaining % others.length;
    for (const t of others) {
      result[t] = base + (mod > 0 ? 1 : 0);
      if (mod > 0) mod--;
    }
    return result;
  }

  const base = Math.floor(total / active.length);
  let mod = total % active.length;
  for (const t of active) {
    result[t] = base + (mod > 0 ? 1 : 0);
    if (mod > 0) mod--;
  }
  return result;
}

const TYPE_WEIGHT_FACTOR: Record<QuestionType, number> = {
  PG: 1,
  JAWABAN_SINGKAT: 1.5,
  MENJODOHKAN: 1.5,
  ESAY: 2.5,
};

const COGNITIVE_DIFFICULTY_FACTOR: Record<CognitiveLevel, number> = {
  C1: 1.0,
  C2: 1.2,
  C3: 2.2,
  C4: 3.5,
  C5: 3.8,
  C6: 4.2,
};

function getQuestionDifficultyRank(q: QuestionItem): number {
  const tier = q.tingkatanSoal || tierFromCognitiveLevel(q.levelKognitif);
  const tierBase = tier === 'LOTS' ? 10 : tier === 'MOTS' ? 20 : 30;
  const cogOffsetMap: Record<CognitiveLevel, number> = {
    C1: 1,
    C2: 2,
    C3: 3,
    C4: 4,
    C5: 5,
    C6: 6,
  };
  return tierBase + (cogOffsetMap[q.levelKognitif] || 2);
}

function getQuestionDifficultyWeight(q: QuestionItem): number {
  const tier = q.tingkatanSoal || tierFromCognitiveLevel(q.levelKognitif);
  const tierAlignedLevel =
    tierFromCognitiveLevel(q.levelKognitif) === tier
      ? q.levelKognitif
      : cognitiveLevelForTier(tier);
  const diffFactor = COGNITIVE_DIFFICULTY_FACTOR[tierAlignedLevel] || 1.2;
  const typeFactor = TYPE_WEIGHT_FACTOR[q.type] || 1;
  return diffFactor * typeFactor;
}

export function isBobotIntegerAndMonotonic(questions: QuestionItem[]): boolean {
  if (questions.length === 0) return true;

  let sum = 0;
  for (const q of questions) {
    const val = Number(q.bobot);
    if (!Number.isInteger(val)) return false;
    if (questions.length <= 100 && val < 1) return false;
    if (val < 0) return false;
    sum += val;
  }
  if (sum !== 100) return false;

  for (let i = 0; i < questions.length; i++) {
    for (let j = i + 1; j < questions.length; j++) {
      if (questions[i].type !== questions[j].type) continue;
      const rankI = getQuestionDifficultyRank(questions[i]);
      const rankJ = getQuestionDifficultyRank(questions[j]);
      if (rankI < rankJ && questions[i].bobot > questions[j].bobot) {
        return false;
      }
      if (rankJ < rankI && questions[j].bobot > questions[i].bobot) {
        return false;
      }
    }
  }

  return true;
}

export function redistributeBobotTotal100(
  questions: QuestionItem[]
): QuestionItem[] {
  const n = questions.length;
  if (n === 0) return [];
  if (n === 1) {
    return [{ ...questions[0], bobot: 100 }];
  }

  const rawWeights = questions.map((q) => getQuestionDifficultyWeight(q));
  const diffRanks = questions.map((q) => getQuestionDifficultyRank(q));
  const totalRaw = rawWeights.reduce((sum, w) => sum + w, 0) || n;
  const minPerQuestion = n <= 100 ? 1 : 0;

  const exactShares = rawWeights.map((w) => (w / totalRaw) * 100);
  const bobots = exactShares.map((exact) =>
    Math.max(minPerQuestion, Math.floor(exact))
  );

  let currentSum = bobots.reduce((sum, val) => sum + val, 0);

  // Jika karena batas minimum bobot=1 jumlah melebihi 100, kurangi dari tingkat kesulitan terendah
  if (currentSum > 100) {
    const indicesLowFirst = bobots
      .map((_, idx) => idx)
      .sort((a, b) => {
        if (diffRanks[a] !== diffRanks[b]) return diffRanks[a] - diffRanks[b];
        return rawWeights[a] - rawWeights[b];
      });
    let guard = 0;
    while (currentSum > 100 && guard < 1000) {
      let reduced = false;
      for (const idx of indicesLowFirst) {
        if (bobots[idx] > minPerQuestion && currentSum > 100) {
          bobots[idx]--;
          currentSum--;
          reduced = true;
        }
      }
      if (!reduced) break;
      guard++;
    }
  }

  // Jika jumlah kurang dari 100, bagikan sisa satuan menggunakan Largest Remainder Method
  // dengan prioritas kesulitan lebih tinggi pada sisa yang berdekatan
  if (currentSum < 100) {
    const indicesByRemainder = bobots
      .map((_, idx) => idx)
      .sort((a, b) => {
        const remA = exactShares[a] - Math.floor(exactShares[a]);
        const remB = exactShares[b] - Math.floor(exactShares[b]);
        if (Math.abs(remB - remA) > 1e-6) return remB - remA;
        if (diffRanks[b] !== diffRanks[a]) return diffRanks[b] - diffRanks[a];
        return rawWeights[b] - rawWeights[a];
      });
    let pointer = 0;
    while (currentSum < 100) {
      const targetIdx = indicesByRemainder[pointer % indicesByRemainder.length];
      bobots[targetIdx]++;
      currentSum++;
      pointer++;
    }
  }

  // Pastikan aturan monotonik: dalam jenis soal yang sama, soal lebih sulit tidak pernah
  // memiliki bobot satuan lebih kecil daripada soal yang lebih mudah
  let swapped = true;
  let passCount = 0;
  while (swapped && passCount < n * n) {
    swapped = false;
    passCount++;
    for (let i = 0; i < n; i++) {
      for (let j = i + 1; j < n; j++) {
        if (questions[i].type !== questions[j].type) continue;
        if (diffRanks[i] < diffRanks[j] && bobots[i] > bobots[j]) {
          const tmp = bobots[i];
          bobots[i] = bobots[j];
          bobots[j] = tmp;
          swapped = true;
        } else if (diffRanks[j] < diffRanks[i] && bobots[j] > bobots[i]) {
          const tmp = bobots[i];
          bobots[i] = bobots[j];
          bobots[j] = tmp;
          swapped = true;
        }
      }
    }
  }

  return questions.map((q, idx) => ({
    ...q,
    bobot: Math.round(bobots[idx]),
  }));
}

export function syncQuestionsWithBabAndTypes(
  existingQuestions: QuestionItem[],
  babList: BabMateriConfig[],
  komposisi: Record<QuestionType, number>,
  selectedTypes: Record<QuestionType, boolean>,
  mataPelajaran: string,
  tingkatanPersentase: Record<QuestionTier, number> = DEFAULT_TINGKATAN_PERSENTASE,
  options?: {
    refreshCpMetadata?: boolean;
    subjectChanged?: boolean;
    kelas?: string;
    fase?: string;
  }
): QuestionItem[] {
  const effectiveFase = options?.fase || INITIAL_METADATA.fase;
  const effectiveKelas =
    options?.kelas ||
    (effectiveFase === 'Fase E' ? 'Kelas X (10)' : 'Kelas XI (11)');

  const effectiveMeta: ExamMetadata = {
    ...INITIAL_METADATA,
    mataPelajaran,
    kelas: effectiveKelas,
    fase: effectiveFase,
    kelasSemester: `${effectiveKelas} / ${effectiveFase}`,
    babMateriList: babList,
  };

  const typesOrder: QuestionType[] = ['PG', 'JAWABAN_SINGKAT', 'MENJODOHKAN', 'ESAY'];
  const activeTypes = typesOrder.filter((t) => selectedTypes[t]);
  if (activeTypes.length === 0) {
    return redistributeBobotTotal100(
      assignTingkatanSoal(existingQuestions, tingkatanPersentase)
    );
  }

  // Bangun antrean bab per slot soal secara round-robin agar semua jenis soal (PG s.d. Esai)
  // merata mengikuti seluruh Bab & Lingkup Materi yang diajarkan sesuai jumlahSoal masing-masing bab
  const remainingPerBab = babList.map((bab) =>
    Math.max(0, Math.floor(bab.jumlahSoal || 0))
  );
  const babSlots: BabMateriConfig[] = [];
  let addedInRound = true;
  while (addedInRound) {
    addedInRound = false;
    for (let bIdx = 0; bIdx < babList.length; bIdx++) {
      if (remainingPerBab[bIdx] > 0) {
        babSlots.push(babList[bIdx]);
        remainingPerBab[bIdx]--;
        addedInRound = true;
      }
    }
  }

  // Bangun daftar jenis soal sesuai komposisi yang dicentang
  const typeSlots: QuestionType[] = [];
  for (const t of activeTypes) {
    const c = Math.max(0, Math.floor(komposisi[t] || 0));
    for (let i = 0; i < c; i++) {
      typeSlots.push(t);
    }
  }

  // Pastikan panjang slot jenis soal cocok dengan jumlah total soal dari semua bab
  if (babSlots.length === 0) {
    typeSlots.length = 0;
  } else {
    while (typeSlots.length < babSlots.length) {
      typeSlots.push(activeTypes[typeSlots.length % activeTypes.length]);
    }
    if (typeSlots.length > babSlots.length) {
      typeSlots.length = babSlots.length;
    }
  }

  const regCode = isAgamaBudiPekertiSubject(mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  const usedExistingIds = new Set<string>();
  const babSeenCount = new Map<string, number>();
  const result: QuestionItem[] = [];

  for (let i = 0; i < typeSlots.length; i++) {
    const nomor = i + 1;
    const targetType = typeSlots[i];
    const targetBab = babSlots[i];
    const babKey = targetBab?.id || '__default__';
    const indexInBab = babSeenCount.get(babKey) || 0;
    babSeenCount.set(babKey, indexInBab + 1);

    // Jika mata pelajaran berubah, susun ulang butir agar sesuai materi & CP mapel baru
    let match = options?.subjectChanged
      ? undefined
      : existingQuestions.find(
          (q) =>
            !usedExistingIds.has(q.id) &&
            q.type === targetType &&
            targetBab &&
            q.babId === targetBab.id
        );
    if (!match && !options?.subjectChanged) {
      match = existingQuestions.find(
        (q) => !usedExistingIds.has(q.id) && q.type === targetType
      );
    }

    if (match) {
      usedExistingIds.add(match.id);
      const updatedMateri = targetBab
        ? `${targetBab.namaBab}${
            targetBab.lingkupMateri ? ` — ${targetBab.lingkupMateri}` : ''
          }`
        : match.materi;
      const babChangedForItem = Boolean(
        targetBab &&
          (match.babId !== targetBab.id ||
            match.namaBab !== targetBab.namaBab ||
            match.materi !== updatedMateri)
      );
      const shouldSyncCp = Boolean(options?.refreshCpMetadata || babChangedForItem);
      const updatedCp =
        !match.manualFields?.kdCp && shouldSyncCp && targetBab
          ? targetBab.capaianPembelajaran
            ? `${targetBab.capaianPembelajaran}${
                targetBab.elemenCp ? ` [Elemen: ${targetBab.elemenCp}]` : ''
              }`
            : `Memahami secara mendalam konsep pada ${updatedMateri} mata pelajaran ${mataPelajaran} (${regShort}).`
          : match.kdCp;

      const updatedTp =
        !match.manualFields?.tujuanPembelajaran &&
        (shouldSyncCp || !match.tujuanPembelajaran)
          ? resolveTpForQuestionInBab(match, targetBab, indexInBab, effectiveMeta)
          : match.tujuanPembelajaran;

      const keepAutoDraft =
        match.isAutoDraft === true ||
        (babChangedForItem && isAutoGeneratedDraftQuestion(match));

      result.push({
        ...match,
        nomor,
        babId: targetBab?.id ?? match.babId,
        namaBab: targetBab?.namaBab ?? match.namaBab,
        materi: targetBab ? updatedMateri : match.materi,
        kdCp: updatedCp,
        tujuanPembelajaran: updatedTp,
        useOptionE: match.type === 'PG' ? true : match.useOptionE,
        isAutoDraft: keepAutoDraft ? true : match.isAutoDraft,
        sumberBuku:
          !match.manualFields?.sumberBuku && shouldSyncCp
            ? `Panduan ${mataPelajaran} ${effectiveKelas} (${effectiveFase}) · ${regShort} (${KURIKULUM_TETAP})`
            : match.sumberBuku,
      });
    } else {
      result.push(
        createEmptyQuestion(
          nomor,
          targetType,
          mataPelajaran,
          targetBab,
          indexInBab,
          effectiveFase,
          effectiveKelas
        )
      );
    }
  }

  // Urutkan rapi berdasarkan jenis soal agar Bagian I-IV tetap terstruktur, lalu beri nomor 1..N
  const ordered: QuestionItem[] = [];
  let finalNo = 1;
  for (const t of typesOrder) {
    for (const q of result.filter((item) => item.type === t)) {
      ordered.push({ ...q, nomor: finalNo++ });
    }
  }

  const withTierAndBobot = redistributeBobotTotal100(
    assignTingkatanSoal(ordered, tingkatanPersentase)
  );

  // Segarkan draf otomatis agar nomor, tingkatan (LOTS/MOTS/HOTS), bobot, TP, & opsi A-E selaras
  const babFinalSeen = new Map<string, number>();
  const initialGenerated = withTierAndBobot.map((q, qIdx) => {
    const matchedBab = babList.find((b) => b.id === q.babId || b.namaBab === q.namaBab);
    const babKey = matchedBab?.id || q.babId || '__default__';
    const idxInBab = babFinalSeen.get(babKey) || 0;
    babFinalSeen.set(babKey, idxInBab + 1);
    const tp = !q.manualFields?.tujuanPembelajaran
      ? resolveTpForQuestionInBab(q, matchedBab, idxInBab, effectiveMeta)
      : q.tujuanPembelajaran || '';

    const variantOffset = idxInBab * 7 + qIdx * 13 + (q.nomor || 1) * 17;

    if (isAutoGeneratedDraftQuestion(q) || options?.refreshCpMetadata) {
      const shouldForceAutoRefresh =
        isAutoGeneratedDraftQuestion(q) || Boolean(options?.subjectChanged);
      return generateSmartDraftContentForQuestion(
        q,
        effectiveMeta,
        tp,
        true,
        shouldForceAutoRefresh,
        variantOffset
      );
    }

    const updatedQ: QuestionItem = {
      ...q,
      tujuanPembelajaran: tp,
      indikator:
        !q.manualFields?.indikator && isAutoGeneratedDraftQuestion(q)
          ? generateSmartIndikatorAbcd(q, effectiveMeta, tp)
          : q.indikator,
    };

    if (updatedQ.type === 'PG' && (!updatedQ.useOptionE || !updatedQ.opsiPg.E?.trim())) {
      return generateSmartDraftContentForQuestion(
        updatedQ,
        effectiveMeta,
        tp,
        true,
        false,
        variantOffset
      );
    }

    return updatedQ;
  });

  // Pastikan tidak ada butir soal yang sama atau double (rumusanSoal unik 100%)
  const seenStems = new Set<string>();
  return initialGenerated.map((q, qIdx) => {
    let stem = (q.rumusanSoal || '').trim();
    if (!seenStems.has(stem)) {
      seenStems.add(stem);
      return q;
    }

    let adjustedQ = q;
    let attempts = 0;
    let altOffset = qIdx * 11 + 7;
    while (seenStems.has(stem) && attempts < 8) {
      attempts++;
      altOffset += 13;
      const matchedBab = babList.find((b) => b.id === q.babId || b.namaBab === q.namaBab);
      const tp = !q.manualFields?.tujuanPembelajaran
        ? resolveTpForQuestionInBab(q, matchedBab, altOffset, effectiveMeta)
        : q.tujuanPembelajaran || '';
      adjustedQ = generateSmartDraftContentForQuestion(
        q,
        effectiveMeta,
        tp,
        true,
        true,
        altOffset
      );
      stem = (adjustedQ.rumusanSoal || '').trim();
    }

    // Jika masih kembar juga, tambahkan penanda variasi unik pada stem agar mutlak berbeda
    if (seenStems.has(stem)) {
      stem = `${stem} (Kasus ${q.nomor}.${qIdx + 1})`;
      adjustedQ = {
        ...adjustedQ,
        rumusanSoal: stem,
      };
    }

    seenStems.add(stem);
    return adjustedQ;
  });
}

