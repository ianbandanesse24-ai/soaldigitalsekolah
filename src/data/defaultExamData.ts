export function tierFromCognitiveLevel(level: CognitiveLevel): QuestionTier {
  if (level === 'C1' || level === 'C2') return 'LOTS';
  if (level === 'C3') return 'MOTS';
  return 'HOTS';
}

export function cognitiveLevelForTier(tier: QuestionTier): CognitiveLevel {
  if (tier === 'LOTS') return 'C2';
  if (tier === 'MOTS') return 'C3';
  return 'C4';
}

export function computeTingkatanCounts(
  total: number,
  persentase: Record<QuestionTier, number> = DEFAULT_TINGKATAN_PERSENTASE
): Record<QuestionTier, number> {
  if (total <= 0) return { LOTS: 0, MOTS: 0, HOTS: 0 };

  const sumPct =
    (persentase.LOTS || 0) + (persentase.MOTS || 0) + (persentase.HOTS || 0) || 100;
  const tiers: QuestionTier[] = ['LOTS', 'MOTS', 'HOTS'];

  const exacts = tiers.map((t) => ({
    tier: t,
    exact: (total * (persentase[t] || 0)) / sumPct,
  }));

  const floors: Record<QuestionTier, number> = {
    LOTS: Math.floor(exacts[0].exact),
    MOTS: Math.floor(exacts[1].exact),
    HOTS: Math.floor(exacts[2].exact),
  };

  let remaining = total - (floors.LOTS + floors.MOTS + floors.HOTS);
  const byRemainder = [...exacts].sort((a, b) => {
    const remA = a.exact - Math.floor(a.exact);
    const remB = b.exact - Math.floor(b.exact);
    return remB - remA;
  });

  let idx = 0;
  while (remaining > 0) {
    floors[byRemainder[idx % byRemainder.length].tier]++;
    remaining--;
    idx++;
  }

  return floors;
}

export function assignTingkatanSoal(
  questions: QuestionItem[],
  persentase: Record<QuestionTier, number> = DEFAULT_TINGKATAN_PERSENTASE
): QuestionItem[] {
  if (questions.length === 0) return [];
  const counts = computeTingkatanCounts(questions.length, persentase);

  // Urutan slot: LOTS (awal, misal no. 1 = LOTS), MOTS (tengah), HOTS (akhir)
  const tierSlots: QuestionTier[] = [
    ...Array(counts.LOTS).fill('LOTS' as QuestionTier),
    ...Array(counts.MOTS).fill('MOTS' as QuestionTier),
    ...Array(counts.HOTS).fill('HOTS' as QuestionTier),
  ];

  let lotsCounter = 0;
  let hotsCounter = 0;
  return questions.map((q, idx) => {
    const tier = tierSlots[idx] || 'MOTS';
    const currentTierFromLevel = tierFromCognitiveLevel(q.levelKognitif);
    let alignedLevel: CognitiveLevel;
    if (currentTierFromLevel === tier) {
      alignedLevel = q.levelKognitif;
    } else if (tier === 'LOTS') {
      alignedLevel = lotsCounter % 2 === 0 ? 'C1' : 'C2';
      lotsCounter++;
    } else if (tier === 'MOTS') {
      alignedLevel = 'C3';
    } else {
      const hotsLevels: CognitiveLevel[] = ['C4', 'C5', 'C6'];
      alignedLevel = hotsLevels[hotsCounter % hotsLevels.length];
      hotsCounter++;
    }
    return {
      ...q,
      tingkatanSoal: tier,
      levelKognitif: alignedLevel,
    };
  });
}

