export function generateSmartDraftContentForQuestion(
  q: QuestionItem,
  metadata: ExamMetadata,
  tpText: string,
  replacePlaceholders = true,
  forceReplaceAutoDraft = false,
  indexWithinBab?: number
): QuestionItem {
  const matchedBab = (metadata.babMateriList || []).find(
    (b) => b.id === q.babId || b.namaBab === q.namaBab
  );
  const babFull = getFullBabLabel(q, matchedBab);
  const babTitle = cleanBabTitle(q, matchedBab);
  const scope = cleanScopeText(q, matchedBab);
  const subtopics = extractSubtopics(scope, babTitle);
  const subIdx =
    indexWithinBab !== undefined
      ? Math.max(0, indexWithinBab)
      : Math.max(0, q.nomor - 1);
  const subtopic = subtopics[subIdx % subtopics.length];
  const altSubtopic = subtopics[(subIdx + 1) % subtopics.length];
  const tier = resolveTier(q);
  const domain = classifySubjectDomain(metadata.mataPelajaran);
  const regCode = isAgamaBudiPekertiSubject(metadata.mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  const blueprint = buildDomainQuestionBlueprint({
    domain,
    subject: metadata.mataPelajaran,
    kelas: metadata.kelas,
    fase: metadata.fase,
    babFull,
    babTitle,
    scope,
    subtopic,
    altSubtopic,
    tier,
    type: q.type,
    variantIdx: subIdx,
  });

  const isManualCp = Boolean(q.manualFields?.kdCp);
  const nextKdCp =
    !isManualCp &&
    (!q.kdCp || q.kdCp.trim() === '-' || q.kdCp.trim().length === 0 || forceReplaceAutoDraft)
      ? matchedBab?.capaianPembelajaran ||
        `Menguasai kompetensi ${babFull} (${scope}) pada mata pelajaran ${metadata.mataPelajaran} ${metadata.fase} sesuai ${regShort}.`
      : q.kdCp;

  const isAutoDraftEligible = q.isAutoDraft !== false;
  const shouldRefreshStem =
    replacePlaceholders &&
    isAutoDraftEligible &&
    (isPlaceholderRumusan(q.rumusanSoal) || forceReplaceAutoDraft || q.isAutoDraft === true);

  const isManualIndikator = Boolean(q.manualFields?.indikator);
  const nextIndikator =
    !isManualIndikator &&
    ((replacePlaceholders && isPlaceholderIndikator(q.indikator)) ||
      (forceReplaceAutoDraft && (isAutoDraftEligible || isPlaceholderIndikator(q.indikator))))
      ? generateSmartIndikatorAbcd(q, metadata, tpText)
      : q.indikator;

  const nextRumusan = shouldRefreshStem ? blueprint.rumusan : q.rumusanSoal;
  let nextOpsiPg = { ...q.opsiPg };
  let nextKunciPg = q.kunciPg;
  let nextUseOptionE = q.type === 'PG' ? true : q.useOptionE;
  let nextKunciSingkat = q.kunciSingkat;
  let nextKunciEsai = q.kunciEsai;
  let nextPairs = [...q.pasanganMenjodohkan];

  // Pilihan jawaban PG WAJIB A - E (useOptionE = true)
  if (q.type === 'PG') {
    nextUseOptionE = true;
    const needOptionsFill =
      replacePlaceholders &&
      isAutoDraftEligible &&
      (isPlaceholderOpsiPg(q.opsiPg) ||
        forceReplaceAutoDraft ||
        q.isAutoDraft === true ||
        !q.opsiPg.E?.trim());

    if (needOptionsFill && blueprint.correctOption && blueprint.distractors) {
      const targetKey = PG_KEYS[subIdx % PG_KEYS.length];
      const filledOpsi: QuestionItem['opsiPg'] = { A: '', B: '', C: '', D: '', E: '' };
      let dIdx = 0;
      for (const k of PG_KEYS) {
        if (k === targetKey) {
          filledOpsi[k] = blueprint.correctOption;
        } else {
          filledOpsi[k] = blueprint.distractors[dIdx % blueprint.distractors.length];
          dIdx++;
        }
      }
      nextOpsiPg = filledOpsi;
      nextKunciPg = targetKey;
    } else if (!nextOpsiPg.E?.trim()) {
      nextOpsiPg = {
        ...nextOpsiPg,
        E: blueprint.distractors?.[3] || `Penerapan konsep ${subtopic} pada ${babTitle}`,
      };
    }
  }

  if (
    replacePlaceholders &&
    isAutoDraftEligible &&
    q.type === 'JAWABAN_SINGKAT' &&
    (isPlaceholderKunciSingkat(q.kunciSingkat) || forceReplaceAutoDraft || q.isAutoDraft === true)
  ) {
    nextKunciSingkat = blueprint.kunciSingkat || subtopic;
  }

  if (
    replacePlaceholders &&
    isAutoDraftEligible &&
    q.type === 'MENJODOHKAN' &&
    (isPlaceholderMatching(q.pasanganMenjodohkan) || forceReplaceAutoDraft || q.isAutoDraft === true)
  ) {
    const bpPairs = blueprint.pairs || [];
    nextPairs = bpPairs.map((pair, idx) => ({
      id: `${q.id}_p${idx + 1}`,
      premise: pair.premise,
      match: pair.match,
    }));
  }

  if (
    replacePlaceholders &&
    isAutoDraftEligible &&
    q.type === 'ESAY' &&
    (isPlaceholderKunciEsai(q.kunciEsai) || forceReplaceAutoDraft || q.isAutoDraft === true)
  ) {
    const s1 = Math.max(1, Math.round(q.bobot * 0.25 * 100) / 100);
    const s2 = Math.max(1, Math.round(q.bobot * 0.45 * 100) / 100);
    const s3 = Math.max(0.5, Math.round((q.bobot - s1 - s2) * 100) / 100);
    const steps = blueprint.kunciEsaiSteps || [
      `Identifikasi konsep dan data utama pada ${subtopic} (${babFull})`,
      `Langkah analisis dan penyelesaian sistematis`,
      `Simpulan akhir yang selaras dengan materi ${metadata.mataPelajaran}`,
    ];
    nextKunciEsai = [
      `1. ${steps[0]} — Skor ${s1}.`,
      `2. ${steps[1]} — Skor ${s2}.`,
      `3. ${steps[2]} — Skor ${s3}.`,
      `Total Skor Maksimal = ${q.bobot}.`,
    ].join('\n');
  }

  const nextSumberBuku =
    !q.manualFields?.sumberBuku && (!q.sumberBuku || forceReplaceAutoDraft || q.isAutoDraft === true)
      ? `Panduan ${metadata.mataPelajaran} ${metadata.kelas} (${metadata.fase}) · ${regShort} (${metadata.kurikulum})`
      : q.sumberBuku;

  const nextUpdatedBase: QuestionItem = {
    ...q,
    kdCp: nextKdCp,
    tujuanPembelajaran: tpText,
    indikator: nextIndikator,
    rumusanSoal: nextRumusan,
    opsiPg: nextOpsiPg,
    useOptionE: nextUseOptionE,
    kunciPg: nextKunciPg,
    kunciSingkat: nextKunciSingkat,
    kunciEsai: nextKunciEsai,
    pasanganMenjodohkan: nextPairs,
    sumberBuku: nextSumberBuku,
    isAutoDraft: shouldRefreshStem ? true : q.isAutoDraft,
    catatanTelaah:
      q.catatanTelaah && q.catatanTelaah.trim().length > 0 && !forceReplaceAutoDraft
        ? q.catatanTelaah
        : `Selaras ${regShort}, ${metadata.kurikulum}, dan tingkatan ${tier} (${q.levelKognitif}).`,
  };

  const nextPembahasan =
    !q.manualFields?.pembahasan &&
    (!q.pembahasan ||
      q.pembahasan.trim().length === 0 ||
      (forceReplaceAutoDraft && isAutoDraftEligible))
      ? blueprint.pembahasanHint || generateDefaultPembahasan(nextUpdatedBase, metadata)
      : q.pembahasan;

  return {
    ...nextUpdatedBase,
    pembahasan: nextPembahasan,
  };
}

export function generateAutoCustomFieldValue(
  headerLabel: string,
  q: QuestionItem,
  metadata: ExamMetadata,
  sampleHint?: string
): string {
  const norm = normalizeCustomFieldKey(headerLabel);
  const tier = resolveTier(q);
  const regCode = isAgamaBudiPekertiSubject(metadata.mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  if (norm.includes('tujuan') || /\batp\b/.test(norm) || /\btp\b/.test(norm)) {
    return q.tujuanPembelajaran || generateDefaultTujuanPembelajaran(q, metadata);
  }
  if (norm.includes('dimensi') || norm.includes('profil')) {
    return 'Penalaran Kritis, Kreativitas, Kolaborasi & Kemandirian (Deep Learning)';
  }
  if (norm.includes('semester') || norm.includes('smt')) {
    return `${metadata.kelas} · Semester Ganjil / Genap (${metadata.fase})`;
  }
  if (norm.includes('tahun')) {
    return metadata.tahunAjaran;
  }
  if (
    norm.includes('sekolah') ||
    norm.includes('satuan pendidikan') ||
    norm.includes('madrasah') ||
    norm.includes('instansi')
  ) {
    return metadata.namaSekolah;
  }
  if (
    norm.includes('penyusun') ||
    norm.includes('pembuat') ||
    norm.includes('penulis') ||
    norm.includes('nama guru')
  ) {
    return metadata.penyusun;
  }
  if (norm === 'nip' || norm.includes('nip ')) {
    return metadata.nipPenyusun || '-';
  }
  if (
    norm.includes('mapel') ||
    norm.includes('mata pelajaran') ||
    norm.includes('studi')
  ) {
    return metadata.mataPelajaran;
  }
  if (norm.includes('kurikulum')) {
    return `${metadata.kurikulum} (${regShort})`;
  }
  if (norm.includes('waktu') || norm.includes('durasi')) {
    return metadata.alokasiWaktu;
  }
  if (
    norm.includes('judul') ||
    norm.includes('nama ujian') ||
    norm.includes('asesmen')
  ) {
    return metadata.judulUjian;
  }
  if (
    norm.includes('kktp') ||
    norm.includes('kriteria') ||
    norm.includes('ketuntasan')
  ) {
    return `Peserta didik mencapai ketuntasan indikator no. ${q.nomor} (${q.materi}) minimal 75%.`;
  }
  if (
    norm.includes('stimulus') ||
    norm.includes('konteks') ||
    norm.includes('wacana')
  ) {
    return `Stimulus kontekstual pada topik ${q.namaBab || q.materi} (${tier} · ${q.levelKognitif}).`;
  }
  if (norm.includes('teknik') || norm.includes('metode')) {
    return `Tes Tertulis — ${SHORT_TYPE_LABELS[q.type]}`;
  }
  if (norm.includes('aspek') || norm.includes('ranah') || norm.includes('domain')) {
    return `Kognitif ${q.levelKognitif} (${tier}) · Pembelajaran Mendalam`;
  }
  if (norm.includes('elemen')) {
    const matchedBab = (metadata.babMateriList || []).find(
      (b) => b.id === q.babId || b.namaBab === q.namaBab
    );
    return (
      matchedBab?.elemenCp ||
      `Elemen CP ${metadata.mataPelajaran} (${metadata.fase})`
    );
  }
  if (
    norm.includes('lingkup') ||
    norm.includes('topik') ||
    norm.includes('sub materi')
  ) {
    return q.materi;
  }
  if (norm.includes('bab')) {
    return q.namaBab || q.materi;
  }
  if (
    norm.includes('penskoran') ||
    norm.includes('rubrik') ||
    norm.includes('skor maks')
  ) {
    return q.type === 'ESAY'
      ? q.kunciEsai ||
          `Skor maksimal ${q.bobot} berdasarkan kelengkapan langkah penyelesaian.`
      : `Jawaban benar diberi skor ${q.bobot}; jawaban salah/kosong skor 0.`;
  }
  if (norm.includes('pembahasan') || norm.includes('penyelesaian')) {
    return generateDefaultPembahasan(q, metadata);
  }
  if (
    norm.includes('validasi') ||
    norm.includes('verifikasi') ||
    norm.includes('penelaah') ||
    norm.includes('keputusan') ||
    norm.includes('status')
  ) {
    return q.catatanTelaah || 'Diterima & layak digunakan';
  }
  if (norm.includes('tanggal') || norm.includes('tgl')) {
    return new Intl.DateTimeFormat('id-ID', {
      day: '2-digit',
      month: 'long',
      year: 'numeric',
    }).format(new Date());
  }
  if (norm.includes('media') || norm.includes('alat') || norm.includes('sumber')) {
    return q.sumberBuku;
  }

  if (
    sampleHint &&
    sampleHint.trim().length > 0 &&
    !/^\(.*isi.*\)$/i.test(sampleHint.trim()) &&
    !/^contoh[:\s]/i.test(sampleHint.trim())
  ) {
    return sampleHint.trim();
  }

  return `${headerLabel}: Penguasaan ${q.materi} pada ${metadata.mataPelajaran} (${metadata.kelas} · ${tier}/${q.levelKognitif})`;
}

export function autoPopulateQuestionsForColumns(
  questions: QuestionItem[],
  metadata: ExamMetadata,
  columns: ReferenceColumnDef[],
  sampleHints?: Record<string, string>,
  options?: {
    smartFillPlaceholders?: boolean;
    forceSyncTpFromBab?: boolean;
    forceRefreshAutoDrafts?: boolean;
    refreshMetadataFields?: boolean;
  }
): QuestionItem[] {
  const babCounterMap = new Map<string, number>();
  const regCode = isAgamaBudiPekertiSubject(metadata.mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  const babList = metadata.babMateriList || [];
  return questions.map((q, qIdx) => {
    let matchedBab = babList.find(
      (b) => b.id === q.babId || b.namaBab === q.namaBab
    );
    if (!matchedBab && options?.refreshMetadataFields && babList.length > 0) {
      matchedBab = babList[qIdx % babList.length];
    }
    const babKey = matchedBab?.id || q.babId || '__default__';
    const indexInBab = babCounterMap.get(babKey) || 0;
    babCounterMap.set(babKey, indexInBab + 1);

    const expectedMateri = matchedBab
      ? `${matchedBab.namaBab}${
          matchedBab.lingkupMateri ? ` — ${matchedBab.lingkupMateri}` : ''
        }`
      : q.materi;

    const syncedBaseQ: QuestionItem =
      options?.refreshMetadataFields && matchedBab
        ? {
            ...q,
            babId: matchedBab.id,
            namaBab: matchedBab.namaBab,
            materi: expectedMateri,
            kdCp:
              !q.manualFields?.kdCp && matchedBab.capaianPembelajaran
                ? `${matchedBab.capaianPembelajaran}${
                    matchedBab.elemenCp ? ` [Elemen: ${matchedBab.elemenCp}]` : ''
                  }`
                : q.kdCp,
          }
        : q;

    const nextTp =
      !syncedBaseQ.manualFields?.tujuanPembelajaran &&
      (options?.forceSyncTpFromBab ||
        options?.refreshMetadataFields ||
        !syncedBaseQ.tujuanPembelajaran ||
        isAutoGeneratedBabTp(syncedBaseQ.tujuanPembelajaran))
        ? resolveTpForQuestionInBab(syncedBaseQ, matchedBab, indexInBab, metadata)
        : syncedBaseQ.tujuanPembelajaran;

    const shouldGenerateSmart = Boolean(
      options?.smartFillPlaceholders ||
        isAutoGeneratedDraftQuestion(syncedBaseQ) ||
        (syncedBaseQ.type === 'PG' && !syncedBaseQ.useOptionE)
    );

    const forceRefreshDraft = Boolean(
      (options?.forceRefreshAutoDrafts || options?.refreshMetadataFields) &&
        isAutoGeneratedDraftQuestion(syncedBaseQ)
    );

    const baseDraftRaw = shouldGenerateSmart
      ? generateSmartDraftContentForQuestion(
          syncedBaseQ,
          metadata,
          nextTp || '',
          true,
          forceRefreshDraft,
          indexInBab
        )
      : {
          ...syncedBaseQ,
          tujuanPembelajaran: nextTp,
          useOptionE: syncedBaseQ.type === 'PG' ? true : syncedBaseQ.useOptionE,
          sumberBuku:
            !q.manualFields?.sumberBuku &&
            (options?.refreshMetadataFields || !q.sumberBuku)
              ? `Panduan ${metadata.mataPelajaran} ${metadata.kelas} (${metadata.fase}) · ${regShort} (${metadata.kurikulum})`
              : q.sumberBuku,
          indikator:
            !syncedBaseQ.manualFields?.indikator &&
            options?.refreshMetadataFields &&
            isPlaceholderIndikator(syncedBaseQ.indikator)
              ? generateSmartIndikatorAbcd(syncedBaseQ, metadata, nextTp)
              : syncedBaseQ.indikator,
          pembahasan:
            !syncedBaseQ.manualFields?.pembahasan &&
            (!syncedBaseQ.pembahasan || syncedBaseQ.pembahasan.trim().length === 0)
              ? generateDefaultPembahasan(syncedBaseQ, metadata)
              : syncedBaseQ.pembahasan,
        };

    const baseDraft: QuestionItem = {
      ...baseDraftRaw,
      sumberBuku:
        !q.manualFields?.sumberBuku && options?.refreshMetadataFields
          ? `Panduan ${metadata.mataPelajaran} ${metadata.kelas} (${metadata.fase}) · ${regShort} (${metadata.kurikulum})`
          : baseDraftRaw.sumberBuku,
    };

    const nextCustomFields: Record<string, string> = {
      ...(baseDraft.customFields || {}),
    };
    const manualCustomKeys = new Set(q.manualFields?.customKeys || []);

    columns.forEach((col) => {
      if (col.mappedField === 'custom') {
        const key = normalizeCustomFieldKey(col.headerLabel);
        if (!key) return;
        const existing = nextCustomFields[key];
        const canRefresh = Boolean(
          options?.refreshMetadataFields && !manualCustomKeys.has(key)
        );
        if (
          !existing ||
          existing.trim() === '-' ||
          existing.trim().length === 0 ||
          canRefresh
        ) {
          const hint =
            col.customValue && col.customValue !== '-'
              ? col.customValue
              : sampleHints?.[key] || sampleHints?.[col.headerLabel];
          nextCustomFields[key] = generateAutoCustomFieldValue(
            col.headerLabel,
            baseDraft,
            metadata,
            hint
          );
        }
      }
    });

    return {
      ...baseDraft,
      customFields: nextCustomFields,
    };
  });
}

export function smartFillWorkFromAcuan(
  questions: QuestionItem[],
  metadata: ExamMetadata,
  columns: ReferenceColumnDef[],
  sampleHints?: Record<string, string>,
  options?: {
    forceSyncTpFromBab?: boolean;
    forceRefreshAutoDrafts?: boolean;
  }
): {
  questions: QuestionItem[];
  filledQuestionsCount: number;
  customFieldsCount: number;
} {
  const populated = autoPopulateQuestionsForColumns(
    questions,
    metadata,
    columns,
    sampleHints,
    {
      smartFillPlaceholders: true,
      forceSyncTpFromBab: options?.forceSyncTpFromBab ?? false,
      forceRefreshAutoDrafts: options?.forceRefreshAutoDrafts ?? false,
    }
  );

  const customColCount = columns.filter((c) => c.mappedField === 'custom').length;
  return {
    questions: populated,
    filledQuestionsCount: populated.length,
    customFieldsCount: customColCount,
  };
}
