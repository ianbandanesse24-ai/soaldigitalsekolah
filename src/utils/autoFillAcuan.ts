const SHORT_TYPE_LABELS: Record<QuestionType, string> = {
  PG: 'Pilihan Ganda',
  ESAY: 'Esai',
  JAWABAN_SINGKAT: 'Jawaban Singkat',
  MENJODOHKAN: 'Menjodohkan',
};

const PG_KEYS: ('A' | 'B' | 'C' | 'D' | 'E')[] = ['A', 'B', 'C', 'D', 'E'];

function resolveTier(q: QuestionItem): QuestionTier {
  if (q.tingkatanSoal) return q.tingkatanSoal;
  if (q.levelKognitif === 'C1' || q.levelKognitif === 'C2') return 'LOTS';
  if (q.levelKognitif === 'C3') return 'MOTS';
  return 'HOTS';
}

export function normalizeCustomFieldKey(headerLabel: string): string {
  return headerLabel
    .toLowerCase()
    .replace(/[:()[\]{}]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function isAutoGeneratedBabTp(tp?: string): boolean {
  const t = (tp || '').trim();
  if (!t) return true;
  return (
    /^Pada Bab|^Pada .*\(lingkup materi|^Melalui pembelajaran .* pada lingkup materi|^Peserta didik mampu (menjelaskan dan mengidentifikasi|menerapkan dan menyelesaikan|menganalisis, mengevaluasi|memahami dan menerapkan|memahami, menelaah, dan merefleksikan|memahami dan menjelaskan|mengevaluasi dan menerapkan) /i.test(
      t
    )
  );
}

export function isPlaceholderRumusan(text?: string): boolean {
  const t = (text || '').trim();
  if (!t || t === '-') return true;
  return (
    /^Tuliskan rumusan butir soal nomor/i.test(t) ||
    /^Rumusan soal nomor/i.test(t) ||
    /^Butir soal nomor/i.test(t) ||
    /^\[Otomatis Data Soal\]/i.test(t) ||
    /^Dalam kajian .* khususnya submateri .* pernyataan/i.test(t) ||
    /^Berdasarkan pemahaman konsep dasar pada .* mengenai/i.test(t) ||
    /^Diketahui kondisi permasalahan pada topik .* melibatkan variabel/i.test(t) ||
    /^Seorang peserta didik mengkaji fenomena kontekstual terkait/i.test(t) ||
    /^Perhatikan permasalahan analitis .* apabila parameter utama/i.test(t) ||
    /^Bacalah kasus kompleks mengenai .* terdapat perbedaan hasil/i.test(t) ||
    /^Pada topik .* istilah atau nilai konstanta\/besaran baku/i.test(t) ||
    /^Konsep utama atau istilah kunci yang menjadi inti pembahasan/i.test(t) ||
    /^Jodohkan aspek konsep pada .* di kolom kiri/i.test(t) ||
    /^Analisislah suatu permasalahan nyata di lingkungan sekitar yang berkaitan dengan/i.test(t) ||
    /^Jelaskan secara sistematis langkah-langkah penyelesaian dan penerapan konsep/i.test(t)
  );
}

export function isPlaceholderIndikator(text?: string): boolean {
  const t = (text || '').trim();
  if (!t || t === '-') return true;
  return (
    /peserta didik dapat menyelesaikan soal nomor \d+/i.test(t) ||
    /^Disajikan (konsep dasar dan pernyataan|permasalahan perhitungan terapan|ilustrasi atau data kasus|stimulus permasalahan kompleks\/kontekstual|pemaparan konsep|data\/stimulus|permasalahan kontekstual) mengenai/i.test(
      t
    )
  );
}

export function isPlaceholderOpsiPg(opsi: QuestionItem['opsiPg']): boolean {
  const a = (opsi.A || '').trim();
  const b = (opsi.B || '').trim();
  return (
    /^Pilihan jawaban A$/i.test(a) ||
    /^Menghubungkan prinsip /i.test(a) ||
    /^Menghubungkan prinsip /i.test(b) ||
    (!a && !b)
  );
}

export function isPlaceholderKunciSingkat(text?: string): boolean {
  const t = (text || '').trim();
  return !t || /^Jawaban benar$/i.test(t) || t === '-';
}

export function isPlaceholderKunciEsai(text?: string): boolean {
  const t = (text || '').trim();
  return (
    !t ||
    /^Tuliskan langkah penyelesaian bermakna/i.test(t) ||
    /^1\. Identifikasi konsep inti & variabel pada /i.test(t) ||
    t === '-'
  );
}

export function isPlaceholderMatching(pairs: MatchingPair[]): boolean {
  if (!pairs || pairs.length === 0) return true;
  return pairs.every(
    (p, i) =>
      new RegExp(`^Pernyataan\\s+${i + 1}$`, 'i').test((p.premise || '').trim()) ||
      new RegExp(`^Pasangan\\s+[A-Z0-9]+$`, 'i').test((p.match || '').trim()) ||
      /^Konsep dasar |^Penerapan |^Evaluasi hasil /i.test((p.premise || '').trim())
  );
}

export function isAutoGeneratedDraftQuestion(q: QuestionItem): boolean {
  return isPlaceholderRumusan(q.rumusanSoal);
}

function cleanScopeText(q: QuestionItem, matchedBab?: BabMateriConfig): string {
  if (matchedBab?.lingkupMateri?.trim()) {
    return matchedBab.lingkupMateri.trim();
  }
  const parts = (q.materi || '').split('—');
  if (parts.length > 1 && parts[1].trim()) return parts[1].trim();
  return (q.namaBab || q.materi || 'Materi Pokok')
    .replace(/^Bab\s*\d+\s*:\s*/i, '')
    .trim();
}

function cleanBabTitle(q: QuestionItem, matchedBab?: BabMateriConfig): string {
  const raw = matchedBab?.namaBab || q.namaBab || q.materi || 'Materi Pokok';
  return raw.replace(/^Bab\s*\d+\s*:\s*/i, '').trim() || raw;
}

function getFullBabLabel(q: QuestionItem, matchedBab?: BabMateriConfig): string {
  return matchedBab?.namaBab || q.namaBab || cleanBabTitle(q, matchedBab);
}

function extractSubtopics(scope: string, fallback: string): string[] {
  const parts = scope
    .split(/[,;&/]+|\bdan\b/i)
    .map((p) => p.trim())
    .filter((p) => p.length > 2);
  return parts.length > 0 ? parts : [fallback];
}

function isCalculationSubject(subject: string): boolean {
  return /matematika|fisika|kimia|ekonomi|akuntansi|informatika|statistika/i.test(
    subject
  );
}

export function generateDefaultTujuanPembelajaran(
  q: QuestionItem,
  metadata: ExamMetadata
): string {
  const matchedBab = (metadata.babMateriList || []).find(
    (b) => b.id === q.babId || b.namaBab === q.namaBab
  );
  const tpList = (matchedBab?.tujuanPembelajaranList || []).filter(
    (tp) => tp.trim().length > 0
  );
  if (tpList.length > 0) {
    return tpList[Math.max(0, (q.nomor - 1) % tpList.length)];
  }

  const babFull = getFullBabLabel(q, matchedBab);
  const scope = cleanScopeText(q, matchedBab);
  const regCode = isAgamaBudiPekertiSubject(metadata.mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;
  const tier = resolveTier(q);
  const verb =
    tier === 'LOTS'
      ? 'menjelaskan dan mengidentifikasi'
      : tier === 'MOTS'
      ? 'menerapkan dan menyelesaikan'
      : 'menganalisis, mengevaluasi, dan memecahkan masalah kontekstual terkait';

  return `Pada ${babFull} (lingkup materi ${scope}), peserta didik mampu ${verb} materi tersebut pada ${metadata.mataPelajaran} (${metadata.kelas} / ${metadata.fase} · ${regShort}).`;
}

export function resolveTpForQuestionInBab(
  q: QuestionItem,
  bab: BabMateriConfig | undefined,
  indexWithinBab: number,
  metadata: ExamMetadata
): string {
  if (bab) {
    const validList = (bab.tujuanPembelajaranList || []).filter(
      (tp) => tp.trim().length > 0
    );
    if (validList.length > 0) {
      return validList[indexWithinBab % validList.length];
    }
    const generatedList = buildDefaultTpsForBab(
      bab.namaBab,
      bab.lingkupMateri,
      metadata.mataPelajaran,
      metadata.fase,
      bab.capaianPembelajaran
    );
    return generatedList[indexWithinBab % generatedList.length];
  }
  return generateDefaultTujuanPembelajaran(q, metadata);
}

export function generateSmartIndikatorAbcd(
  q: QuestionItem,
  metadata: ExamMetadata,
  tpText?: string
): string {
  const matchedBab = (metadata.babMateriList || []).find(
    (b) => b.id === q.babId || b.namaBab === q.namaBab
  );
  const scope = cleanScopeText(q, matchedBab);
  const subtopics = extractSubtopics(scope, cleanBabTitle(q, matchedBab));
  const subtopic = subtopics[Math.max(0, (q.nomor - 1) % subtopics.length)];
  const babLabel = getFullBabLabel(q, matchedBab);
  const tier = resolveTier(q);
  const isCalc = isCalculationSubject(metadata.mataPelajaran);

  const condition =
    tier === 'LOTS'
      ? `Disajikan pemaparan konsep dasar mengenai ${subtopic} pada ${babLabel}`
      : tier === 'MOTS'
      ? isCalc
        ? `Disajikan permasalahan perhitungan terapan mengenai ${subtopic} (${babLabel})`
        : `Disajikan data atau ilustrasi kasus mengenai ${subtopic} (${babLabel})`
      : `Disajikan stimulus permasalahan kompleks/kontekstual mengenai ${subtopic} (${babLabel})`;

  const behavior =
    q.type === 'PG'
      ? tier === 'LOTS'
        ? 'mengidentifikasi pengertian, ciri, atau prinsip yang paling tepat melalui pilihan A–E'
        : tier === 'MOTS'
        ? isCalc
          ? 'menentukan hasil penyelesaian secara cermat dan akurat pada pilihan A–E'
          : 'menerapkan konsep yang tepat untuk memecahkan permasalahan tersebut'
        : 'menganalisis keterkaitan antarvariabel serta menyimpulkan solusi paling rasional'
      : q.type === 'JAWABAN_SINGKAT'
      ? isCalc
        ? 'menghitung dan menuliskan nilai/besaran hasil akhirnya secara singkat dan tepat'
        : 'menuliskan istilah kunci atau konsep inti secara ringkas dan tepat'
      : q.type === 'MENJODOHKAN'
      ? 'memasangkan konsep/pernyataan pada kolom kiri dengan deskripsi/rumus padanannya di kolom kanan secara tepat'
      : 'menguraikan langkah analisis, penalaran logis, serta kesimpulan penyelesaian secara sistematis';

  const tpSuffix = tpText ? '' : ` (${metadata.mataPelajaran} ${metadata.kelas})`;
  return `${condition}, peserta didik dapat ${behavior}${tpSuffix} dengan benar.`;
}

export function generateDefaultPembahasan(
  q: QuestionItem,
  metadata: ExamMetadata
): string {
  const tier = resolveTier(q);
  if (q.type === 'PG') {
    const kunciVal = q.opsiPg[q.kunciPg] || '';
    return `Jawaban yang benar adalah ${q.kunciPg}${
      kunciVal ? ` (${kunciVal})` : ''
    } karena selaras dengan konsep ${q.materi} (${tier} · ${q.levelKognitif} · ${metadata.mataPelajaran}).`;
  }
  if (q.type === 'JAWABAN_SINGKAT') {
    return `Kunci jawaban singkat: ${q.kunciSingkat || '-'} berdasarkan ruang lingkup ${q.materi} (${metadata.mataPelajaran}).`;
  }
  if (q.type === 'MENJODOHKAN') {
    return `Pasangan konsep disusun berdasarkan hubungan definisi dan penerapan pada materi ${q.materi} (${q.pasanganMenjodohkan.length} pasangan).`;
  }
  return `Penilaian uraian mengacu pada ketepatan identifikasi konsep, kelengkapan langkah penyelesaian runtut, dan simpulan logis pada topik ${q.materi} (skor maks. ${q.bobot}).`;
}

export function generateSmartDraftContentForQuestion(
  q: QuestionItem,
  metadata: ExamMetadata,
  tpText: string,
  replacePlaceholders = true,
  forceReplaceAutoDraft = false
): QuestionItem {
  const matchedBab = (metadata.babMateriList || []).find(
    (b) => b.id === q.babId || b.namaBab === q.namaBab
  );
  const babFull = getFullBabLabel(q, matchedBab);
  const babTitle = cleanBabTitle(q, matchedBab);
  const scope = cleanScopeText(q, matchedBab);
  const subtopics = extractSubtopics(scope, babTitle);
  const subIdx = Math.max(0, q.nomor - 1);
  const subtopic = subtopics[subIdx % subtopics.length];
  const altSubtopic = subtopics[(subIdx + 1) % subtopics.length];
  const tier = resolveTier(q);
  const isCalc = isCalculationSubject(metadata.mataPelajaran);
  const regCode = isAgamaBudiPekertiSubject(metadata.mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  const nextKdCp =
    !q.kdCp || q.kdCp.trim() === '-' || q.kdCp.trim().length === 0 || forceReplaceAutoDraft
      ? matchedBab?.capaianPembelajaran ||
        `Menguasai kompetensi ${babFull} (${scope}) pada ${metadata.mataPelajaran} ${metadata.fase} sesuai ${regShort}.`
      : q.kdCp;

  const shouldRefreshStem =
    replacePlaceholders &&
    (isPlaceholderRumusan(q.rumusanSoal) || forceReplaceAutoDraft);

  const nextIndikator =
    (replacePlaceholders && isPlaceholderIndikator(q.indikator)) ||
    forceReplaceAutoDraft
      ? generateSmartIndikatorAbcd(q, metadata, tpText)
      : q.indikator;

  let nextRumusan = q.rumusanSoal;
  let nextOpsiPg = { ...q.opsiPg };
  let nextKunciPg = q.kunciPg;
  let nextUseOptionE = q.type === 'PG' ? true : q.useOptionE;
  let nextKunciSingkat = q.kunciSingkat;
  let nextKunciEsai = q.kunciEsai;
  let nextPairs = [...q.pasanganMenjodohkan];

  if (shouldRefreshStem) {
    if (q.type === 'PG') {
      if (tier === 'LOTS') {
        nextRumusan = isCalc
          ? `Pada pembelajaran ${babFull} dengan lingkup materi ${subtopic} (${metadata.mataPelajaran} ${metadata.kelas}), pernyataan prinsip dasar atau hubungan variabel yang paling tepat adalah ....`
          : `Dalam kajian ${babFull} khususnya lingkup materi ${subtopic} pada ${metadata.mataPelajaran} (${metadata.fase}), konsep atau pernyataan dasar yang paling tepat adalah ....`;
      } else if (tier === 'MOTS') {
        nextRumusan = isCalc
          ? `Diketahui suatu permasalahan terapan pada ${babFull} mengenai ${subtopic} yang melibatkan relasi variabel x dan y secara terukur. Pendekatan penerapan konsep yang paling tepat untuk menyelesaikan kasus tersebut adalah ....`
          : `Seorang peserta didik mengkaji studi kasus kontekstual tentang ${subtopic} dalam ${babFull} (${metadata.mataPelajaran} ${metadata.kelas}). Penerapan prinsip yang paling tepat untuk menyelesaikan kasus tersebut adalah ....`;
      } else {
        nextRumusan = isCalc
          ? `Perhatikan analisis ${subtopic} pada ${babFull}: apabila salah satu parameter utama berubah menjadi dua kali nilai awal sementara kondisi batas dipertahankan, simpulan analitis yang paling rasional adalah ....`
          : `Cermati fenomena kompleks terkait ${subtopic} dan ${altSubtopic} pada ${babFull}: terjadi kesenjangan antara kondisi ideal konsep dan realitas lapangan. Berdasarkan penalaran kritis Kurikulum Deep Learning, evaluasi dan solusi paling tepat adalah ....`;
      }
    } else if (q.type === 'JAWABAN_SINGKAT') {
      nextRumusan = isCalc
        ? `Pada ${babFull} (lingkup materi ${subtopic}), istilah baku atau besaran utama yang menjadi dasar perhitungan konsep tersebut dalam ${metadata.mataPelajaran} (${metadata.kelas}) adalah ....`
        : `Istilah kunci atau konsep inti yang menjadi pokok bahasan utama pada ${subtopic} (${babFull} · ${metadata.mataPelajaran}) adalah ....`;
    } else if (q.type === 'MENJODOHKAN') {
      nextRumusan = `Jodohkan konsep/aspek dari ${babFull} (lingkup materi ${scope}) pada kolom kiri dengan penjelasan atau penerapannya yang tepat pada kolom kanan!`;
    } else {
      nextRumusan =
        tier === 'HOTS'
          ? `Analisislah suatu permasalahan kontekstual nyata yang berkaitan dengan ${subtopic} pada ${babFull} (${metadata.mataPelajaran} ${metadata.kelas})! Uraikan identifikasi masalah, keterkaitan dengan ${altSubtopic}, serta solusi bermakna yang dapat diterapkan!`
          : `Jelaskan secara sistematis konsep ${subtopic} pada ${babFull} (${metadata.mataPelajaran} ${metadata.fase}), lengkapi dengan langkah penerapan serta contoh nyata dalam kehidupan sehari-hari!`;
    }
  }

  // Pilihan jawaban PG WAJIB A - E (useOptionE = true)
  if (q.type === 'PG') {
    nextUseOptionE = true;
    const needOptionsFill =
      replacePlaceholders &&
      (isPlaceholderOpsiPg(q.opsiPg) || forceReplaceAutoDraft || !q.opsiPg.E?.trim());

    if (needOptionsFill) {
      const targetKey = PG_KEYS[subIdx % PG_KEYS.length];
      const correctOption = isCalc
        ? `Menerapkan hukum/rumus ${subtopic} sesuai syarat batas ${babTitle} secara konsisten dan terukur`
        : `Mengintegrasikan prinsip inti ${subtopic} dengan bukti dan konteks ${babTitle} secara logis`;

      const distractors = isCalc
        ? [
            `Mengabaikan syarat batas variabel pada ${subtopic} tanpa verifikasi satuan`,
            `Menyamakan seluruh koefisien ${subtopic} dengan nilai konstan tanpa analisis`,
            `Menggunakan relasi terbalik yang bertentangan dengan hukum dasar ${babTitle}`,
            `Menetapkan simpulan langsung tanpa memvalidasi persamaan ${subtopic}`,
          ]
        : [
            `Menarik simpulan umum mengenai ${subtopic} tanpa dukungan fakta atau dalil ${babTitle}`,
            `Memisahkan konsep ${subtopic} dari konteks nyata maupun prinsip ${babTitle}`,
            `Mengutamakan asumsi subjektif yang bertentangan dengan kaidah ${metadata.mataPelajaran}`,
            `Menyamakan seluruh kasus ${subtopic} tanpa mempertimbangkan kondisi faktual`,
          ];

      const filledOpsi: QuestionItem['opsiPg'] = { A: '', B: '', C: '', D: '', E: '' };
      let dIdx = 0;
      for (const k of PG_KEYS) {
        if (k === targetKey) {
          filledOpsi[k] = correctOption;
        } else {
          filledOpsi[k] = distractors[dIdx % distractors.length];
          dIdx++;
        }
      }
      nextOpsiPg = filledOpsi;
      nextKunciPg = targetKey;
    } else if (!nextOpsiPg.E?.trim()) {
      nextOpsiPg = {
        ...nextOpsiPg,
        E: `Alternatif jawaban E sesuai analisis ${subtopic} pada ${babTitle}`,
      };
    }
  }

  if (
    replacePlaceholders &&
    q.type === 'JAWABAN_SINGKAT' &&
    (isPlaceholderKunciSingkat(q.kunciSingkat) || forceReplaceAutoDraft)
  ) {
    nextKunciSingkat = subtopic;
  }

  if (
    replacePlaceholders &&
    q.type === 'MENJODOHKAN' &&
    (isPlaceholderMatching(q.pasanganMenjodohkan) || forceReplaceAutoDraft)
  ) {
    const t0 = subtopics[0] || babTitle;
    const t1 = subtopics[1] || `Penerapan ${babTitle}`;
    const t2 = subtopics[2] || `Evaluasi ${babTitle}`;
    nextPairs = [
      {
        id: `${q.id}_p1`,
        premise: `Konsep inti ${t0}`,
        match: `Prinsip dasar utama pada ${babFull}`,
      },
      {
        id: `${q.id}_p2`,
        premise: `Implementasi ${t1}`,
        match: `Pemecahan masalah kontekstual ${metadata.mataPelajaran} (${metadata.fase})`,
      },
      {
        id: `${q.id}_p3`,
        premise: `Analisis & refleksi ${t2}`,
        match: `Verifikasi ketepatan simpulan berbasis ${tier}`,
      },
    ];
  }

  if (
    replacePlaceholders &&
    q.type === 'ESAY' &&
    (isPlaceholderKunciEsai(q.kunciEsai) || forceReplaceAutoDraft)
  ) {
    const s1 = Math.max(1, Math.round(q.bobot * 0.25 * 100) / 100);
    const s2 = Math.max(1, Math.round(q.bobot * 0.45 * 100) / 100);
    const s3 = Math.max(0.5, Math.round((q.bobot - s1 - s2) * 100) / 100);
    nextKunciEsai = [
      `1. Identifikasi konsep & data kunci pada ${subtopic} (${babFull}) — Skor ${s1}.`,
      `2. Langkah analisis/penyelesaian sistematis dan argumentatif — Skor ${s2}.`,
      `3. Simpulan akhir & keterkaitan kontekstual terhadap TP (${metadata.mataPelajaran}) — Skor ${s3}.`,
      `Total Skor Maksimal = ${q.bobot}.`,
    ].join('\n');
  }

  const nextSumberBuku =
    !q.sumberBuku || forceReplaceAutoDraft
      ? `Panduan ${metadata.mataPelajaran} ${metadata.kelas} (${metadata.fase}) · ${regShort} (${metadata.kurikulum})`
      : q.sumberBuku;

  const nextUpdatedBase: QuestionItem = {
    ...q,
    kdCp: nextKdCp,
    tujuanPembelajaran: tpText,
    indikator: nextIndikator,
    rumusanSoal: nextRumusan,
    opsiPg: nextOpsiPg,
    useOptionE: nextUseOptionE,
    kunciPg: nextKunciPg,
    kunciSingkat: nextKunciSingkat,
    kunciEsai: nextKunciEsai,
    pasanganMenjodohkan: nextPairs,
    sumberBuku: nextSumberBuku,
    catatanTelaah:
      q.catatanTelaah && q.catatanTelaah.trim().length > 0 && !forceReplaceAutoDraft
        ? q.catatanTelaah
        : `Selaras ${regShort}, ${metadata.kurikulum}, dan tingkatan ${tier} (${q.levelKognitif}).`,
  };

  const nextPembahasan =
    !q.pembahasan || q.pembahasan.trim().length === 0 || forceReplaceAutoDraft
      ? generateDefaultPembahasan(nextUpdatedBase, metadata)
      : q.pembahasan;

  return {
    ...nextUpdatedBase,
    pembahasan: nextPembahasan,
  };
}

export function generateAutoCustomFieldValue(
  headerLabel: string,
  q: QuestionItem,
  metadata: ExamMetadata,
  sampleHint?: string
): string {
  const norm = normalizeCustomFieldKey(headerLabel);
  const tier = resolveTier(q);
  const regCode = isAgamaBudiPekertiSubject(metadata.mataPelajaran)
    ? 'CP_020_2026'
    : 'CP_046_2025';
  const regShort = CP_REGULATIONS[regCode].short;

  if (norm.includes('tujuan') || /\batp\b/.test(norm) || /\btp\b/.test(norm)) {
    return q.tujuanPembelajaran || generateDefaultTujuanPembelajaran(q, metadata);
  }
  if (norm.includes('dimensi') || norm.includes('profil')) {
    return 'Penalaran Kritis, Kreativitas, Kolaborasi & Kemandirian (Deep Learning)';
  }
  if (norm.includes('semester') || norm.includes('smt')) {
    return `${metadata.kelas} · Semester Ganjil / Genap (${metadata.fase})`;
  }
  if (norm.includes('tahun')) {
    return metadata.tahunAjaran;
  }
  if (
    norm.includes('sekolah') ||
    norm.includes('satuan pendidikan') ||
    norm.includes('madrasah') ||
    norm.includes('instansi')
  ) {
    return metadata.namaSekolah;
  }
  if (
    norm.includes('penyusun') ||
    norm.includes('pembuat') ||
    norm.includes('penulis') ||
    norm.includes('nama guru')
  ) {
    return metadata.penyusun;
  }
  if (norm === 'nip' || norm.includes('nip ')) {
    return metadata.nipPenyusun || '-';
  }
  if (
    norm.includes('mapel') ||
    norm.includes('mata pelajaran') ||
    norm.includes('studi')
  ) {
    return metadata.mataPelajaran;
  }
  if (norm.includes('kurikulum')) {
    return `${metadata.kurikulum} (${regShort})`;
  }
  if (norm.includes('waktu') || norm.includes('durasi')) {
    return metadata.alokasiWaktu;
  }
  if (
    norm.includes('judul') ||
    norm.includes('nama ujian') ||
    norm.includes('asesmen')
  ) {
    return metadata.judulUjian;
  }
  if (
    norm.includes('kktp') ||
    norm.includes('kriteria') ||
    norm.includes('ketuntasan')
  ) {
    return `Peserta didik mencapai ketuntasan indikator no. ${q.nomor} (${q.materi}) minimal 75%.`;
  }
  if (
    norm.includes('stimulus') ||
    norm.includes('konteks') ||
    norm.includes('wacana')
  ) {
    return `Stimulus kontekstual pada topik ${q.namaBab || q.materi} (${tier} · ${q.levelKognitif}).`;
  }
  if (norm.includes('teknik') || norm.includes('metode')) {
    return `Tes Tertulis — ${SHORT_TYPE_LABELS[q.type]}`;
  }
  if (norm.includes('aspek') || norm.includes('ranah') || norm.includes('domain')) {
    return `Kognitif ${q.levelKognitif} (${tier}) · Pembelajaran Mendalam`;
  }
  if (norm.includes('elemen')) {
    const matchedBab = (metadata.babMateriList || []).find(
      (b) => b.id === q.babId || b.namaBab === q.namaBab
    );
    return (
      matchedBab?.elemenCp ||
      `Elemen CP ${metadata.mataPelajaran} (${metadata.fase})`
    );
  }
  if (
    norm.includes('lingkup') ||
    norm.includes('topik') ||
    norm.includes('sub materi')
  ) {
    return q.materi;
  }
  if (norm.includes('bab')) {
    return q.namaBab || q.materi;
  }
  if (
    norm.includes('penskoran') ||
    norm.includes('rubrik') ||
    norm.includes('skor maks')
  ) {
    return q.type === 'ESAY'
      ? q.kunciEsai ||
          `Skor maksimal ${q.bobot} berdasarkan kelengkapan langkah penyelesaian.`
      : `Jawaban benar diberi skor ${q.bobot}; jawaban salah/kosong skor 0.`;
  }
  if (norm.includes('pembahasan') || norm.includes('penyelesaian')) {
    return generateDefaultPembahasan(q, metadata);
  }
  if (
    norm.includes('validasi') ||
    norm.includes('verifikasi') ||
    norm.includes('penelaah') ||
    norm.includes('keputusan') ||
    norm.includes('status')
  ) {
    return q.catatanTelaah || 'Diterima & layak digunakan';
  }
  if (norm.includes('tanggal') || norm.includes('tgl')) {
    return new Intl.DateTimeFormat('id-ID', {
      day: '2-digit',
      month: 'long',
      year: 'numeric',
    }).format(new Date());
  }
  if (norm.includes('media') || norm.includes('alat') || norm.includes('sumber')) {
    return q.sumberBuku;
  }

  if (
    sampleHint &&
    sampleHint.trim().length > 0 &&
    !/^\(.*isi.*\)$/i.test(sampleHint.trim()) &&
    !/^contoh[:\s]/i.test(sampleHint.trim())
  ) {
    return sampleHint.trim();
  }

  return `${headerLabel}: Penguasaan ${q.materi} pada ${metadata.mataPelajaran} (${metadata.kelas} · ${tier}/${q.levelKognitif})`;
}

export function autoPopulateQuestionsForColumns(
  questions: QuestionItem[],
  metadata: ExamMetadata,
  columns: ReferenceColumnDef[],
  sampleHints?: Record<string, string>,
  options?: {
    smartFillPlaceholders?: boolean;
    forceSyncTpFromBab?: boolean;
    forceRefreshAutoDrafts?: boolean;
  }
): QuestionItem[] {
  const babCounterMap = new Map<string, number>();

  return questions.map((q) => {
    const matchedBab = (metadata.babMateriList || []).find(
      (b) => b.id === q.babId || b.namaBab === q.namaBab
    );
    const babKey = matchedBab?.id || q.babId || '__default__';
    const indexInBab = babCounterMap.get(babKey) || 0;
    babCounterMap.set(babKey, indexInBab + 1);

    const nextTp =
      options?.forceSyncTpFromBab ||
      !q.tujuanPembelajaran ||
      isAutoGeneratedBabTp(q.tujuanPembelajaran)
        ? resolveTpForQuestionInBab(q, matchedBab, indexInBab, metadata)
        : q.tujuanPembelajaran;

    const shouldGenerateSmart = Boolean(
      options?.smartFillPlaceholders ||
        isPlaceholderRumusan(q.rumusanSoal) ||
        (q.type === 'PG' && !q.useOptionE)
    );

    const baseDraft = shouldGenerateSmart
      ? generateSmartDraftContentForQuestion(
          q,
          metadata,
          nextTp,
          true,
          Boolean(options?.forceRefreshAutoDrafts && isAutoGeneratedDraftQuestion(q))
        )
      : {
          ...q,
          tujuanPembelajaran: nextTp,
          useOptionE: q.type === 'PG' ? true : q.useOptionE,
          pembahasan:
            !q.pembahasan || q.pembahasan.trim().length === 0
              ? generateDefaultPembahasan(q, metadata)
              : q.pembahasan,
        };

    const nextCustomFields: Record<string, string> = {
      ...(baseDraft.customFields || {}),
    };

    columns.forEach((col) => {
      if (col.mappedField === 'custom') {
        const key = normalizeCustomFieldKey(col.headerLabel);
        if (!key) return;
        const existing = nextCustomFields[key];
        if (!existing || existing.trim() === '-' || existing.trim().length === 0) {
          const hint =
            col.customValue && col.customValue !== '-'
              ? col.customValue
              : sampleHints?.[key] || sampleHints?.[col.headerLabel];
          nextCustomFields[key] = generateAutoCustomFieldValue(
            col.headerLabel,
            baseDraft,
            metadata,
            hint
          );
        }
      }
    });

    return {
      ...baseDraft,
      customFields: nextCustomFields,
    };
  });
}

export function smartFillWorkFromAcuan(
  questions: QuestionItem[],
  metadata: ExamMetadata,
  columns: ReferenceColumnDef[],
  sampleHints?: Record<string, string>,
  options?: {
    forceSyncTpFromBab?: boolean;
    forceRefreshAutoDrafts?: boolean;
  }
): {
  questions: QuestionItem[];
  filledQuestionsCount: number;
  customFieldsCount: number;
} {
  const populated = autoPopulateQuestionsForColumns(
    questions,
    metadata,
    columns,
    sampleHints,
    {
      smartFillPlaceholders: true,
      forceSyncTpFromBab: options?.forceSyncTpFromBab ?? false,
      forceRefreshAutoDrafts: options?.forceRefreshAutoDrafts ?? false,
    }
  );

  const customColCount = columns.filter((c) => c.mappedField === 'custom').length;
  return {
    questions: populated,
    filledQuestionsCount: populated.length,
    customFieldsCount: customColCount,
  };
}
