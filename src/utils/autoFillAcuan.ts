  const cleanAlt = stripOuterQuotesAndPunct(altSubtopic);
  const cleanBab = stripOuterQuotesAndPunct(babTitle);
  const topicText = `${babTitle} ${scope}`.toLowerCase();

  // 1. PILIHAN GANDA (PG)
